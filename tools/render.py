        f"hostname {hostname}",
        "!",
        "no ip domain-lookup",
        f"ip domain-name {d['domain']}",
        "!",
        f"enable algorithm-type scrypt secret {SECRET}",
        f"username netadmin privilege 15 algorithm-type scrypt secret {SECRET}",
        "!",
