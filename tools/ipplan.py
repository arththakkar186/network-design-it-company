#!/usr/bin/env python3
"""Generate docs/ip-address-plan.md from design/network.json.

    python3 tools/ipplan.py          # write the document
    python3 tools/ipplan.py --check  # exit 1 if the committed document is stale
"""
from __future__ import annotations

import argparse
import ipaddress
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from render import ROOT, load  # noqa: E402

DOC = ROOT / "docs" / "ip-address-plan.md"


def dhcp_scope(n: ipaddress.IPv4Network, reserve_low: int) -> str:
    first = n.network_address + reserve_low + 1
    last = n.broadcast_address - 1
    return f"{first} - {last}"


def build(d: dict) -> str:
    hq, br, w = d["sites"]["hq"], d["sites"]["branch"], d["wan"]
    out = [
        "# IP Address Plan",
        "",
        "> Generated by `tools/ipplan.py` from `design/network.json`. Do not edit by hand.",
        "",
        "## Allocation strategy",
        "",
        "- **HQ** uses `10.10.0.0/16`, **branch** uses `10.20.0.0/16`. One /16 per site means each site",
        "  can be summarised as a single route and the second octet always tells you the site.",
        "- **Third octet = VLAN ID** wherever possible (VLAN 30 is `10.10.30.0`), so anyone can read a",
        "  VLAN from an address during troubleshooting.",
        "- **VLSM**: subnets are sized to demand. Engineering and corporate Wi-Fi get a /23, servers a /26,",
        "  the hub lab a /27 and point-to-point links a /30.",
        "- **Reserved low addresses** in every user VLAN: `.1` HSRP virtual gateway, `.2` CORE1, `.3` CORE2,",
        "  `.4`-`.20` static/reserved (printers, phones needing reservations). DHCP hands out the rest.",
        "- `10.10.254.0/24` loopbacks, `10.10.255.0/24` routed links, `172.16.0.0/30` VPN tunnel.",
        "- Public addresses are RFC 5737 documentation ranges (`203.0.113.0/24`, `198.51.100.0/24`).",
        "",
        "## HQ VLANs",
        "",
        "| VLAN | Name | Subnet | Mask | Usable hosts | Gateway (HSRP VIP) | CORE1 / CORE2 | HSRP active | DHCP scope | Purpose |",
        "|---:|---|---|---|---:|---|---|---|---|---|",
    ]
    total = 0
    for v in hq["vlans"]:
        n = ipaddress.ip_network(v["subnet"])
        usable = n.num_addresses - 2
        total += usable
        scope = "static only" if v["name"] in ("SERVERS",) else dhcp_scope(n, 20 if n.prefixlen <= 24 else 10)
        out.append(
            f"| {v['id']} | {v['name']} | `{n}` | {n.netmask} | {usable} | {n.network_address + 1} | "
            f"{n.network_address + 2} / {n.network_address + 3} | {v['hsrp_active']} | {scope} | {v['purpose']} |"
        )
    out += [
        f"| {hq['blackhole_vlan']['id']} | {hq['blackhole_vlan']['name']} | none | | | | | | | Unused ports and trunk native VLAN. Never routed. |",
        "",
        f"Total usable HQ host addresses across user/service VLANs: **{total:,}** for about 120 staff,",
        "leaving room for phones, Wi-Fi devices (2-3 per person) and growth.",
        "",
        "## HQ infrastructure addresses",
        "",
        "| Device | Interface | Address | Notes |",
        "|---|---|---|---|",
    ]
    for dev, ip in hq["loopbacks"].items():
        out.append(f"| {dev} | Loopback0 | `{ip}/32` | OSPF router ID, management source |")
    for link in hq["routed_links"]:
        for end in ("a", "b"):
            e = link[end]
            out.append(f"| {e['device']} | {e['intf']} | `{e['ip']}/{link['subnet'].split('/')[1]}` | {link['name']} point-to-point |")
    for sw in hq["access_switches"]:
        out.append(f"| {sw['name']} | Vlan10 | `{sw['mgmt_ip']}/24` | {sw['model']}, {sw['location']} |")
    out += ["", "## HQ servers", "", "| Server | Address | Role |", "|---|---|---|"]
    for s in hq["servers"]:
        out.append(f"| {s['name']} | `{s['ip']}` | {s['role']} |")
    out += [
        "",
        "## Branch",
        "",
        "| VLAN | Name | Subnet | Gateway (R-BR sub-interface) | Purpose |",
        "|---:|---|---|---|---|",
    ]
    for v in br["vlans"]:
        n = ipaddress.ip_network(v["subnet"])
        out.append(f"| {v['id']} | {v['name']} | `{n}` | {n.network_address + 1} | {v['purpose']} |")
    out += [
        f"| - | R-BR Loopback0 | `{br['router']['loopback']}/32` | | OSPF router ID |",
        f"| 110 | {br['switch']['name']} | `{br['switch']['mgmt_ip']}/24` | | Switch management |",
        "",
        "## WAN",
        "",
        "| Link | Address | Peer / gateway |",
        "|---|---|---|",
        f"| HQ internet ({w['hq_public']['device']} {w['hq_public']['intf']}) | `{w['hq_public']['ip']}/{w['hq_public']['prefix']}` | {w['hq_public']['gateway']} |",
        f"| Branch internet ({w['branch_public']['device']} {w['branch_public']['intf']}) | `{w['branch_public']['ip']}/{w['branch_public']['prefix']}` | {w['branch_public']['gateway']} |",
        f"| Tunnel{w['tunnel']['id']} GRE over IPsec | HQ `{w['tunnel']['hq_ip']}` / branch `{w['tunnel']['branch_ip']}` | `{w['tunnel']['subnet']}` |",
        "",
    ]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build(load())
    if a.check:
        if not DOC.exists() or DOC.read_text() != text:
            print("docs/ip-address-plan.md is stale. Run python3 tools/ipplan.py", file=sys.stderr)
            return 1
        print("docs/ip-address-plan.md is current")
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
