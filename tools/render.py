        "snmp-server view NETOPS-VIEW iso included",
        f"snmp-server user nms NETOPS v3 auth sha {SECRET} priv aes 128 {SECRET}",
        f"snmp-server host {s['snmp_manager']} version 3 priv nms",
        "ip access-list standard SNMP-ALLOWED",
