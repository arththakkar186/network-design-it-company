def render_all(d: dict) -> dict[str, str]:
    out = {
        "hq/R-EDGE.cfg": render_edge(d),
        "hq/CORE1.cfg": render_core(d, "CORE1"),
        "hq/CORE2.cfg": render_core(d, "CORE2"),
        "branch/R-BR.cfg": render_branch_router(d),
        "branch/SW-BR-01.cfg": render_branch_switch(d),
    }
    for sw in d["sites"]["hq"]["access_switches"]:
        out[f"hq/{sw['name']}.cfg"] = render_access(d, sw)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if committed configs differ from a fresh render")
    args = ap.parse_args(argv)
    rendered = render_all(load())
    stale = []
    for rel, text in sorted(rendered.items()):
        path = OUT / rel
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote configs/{rel} ({text.count(chr(10))} lines)")
    if args.check:
        if stale:
            print("Out of date: " + ", ".join(stale) + ". Run python3 tools/render.py", file=sys.stderr)
            return 1
        print(f"All {len(rendered)} configs match design/network.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
