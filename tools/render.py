#!/usr/bin/env python3
"""Render Cisco IOS / IOS-XE configurations from design/network.json.

Standard library only. Usage:

    python3 tools/render.py            # writes configs/hq/*.cfg and configs/branch/*.cfg
    python3 tools/render.py --check    # exits 1 if the committed configs are out of date

Secrets are never rendered. Every credential is the literal placeholder
CHANGE_ME, which must be replaced at deployment time (see docs/06-implementation-plan.md).
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "design" / "network.json"
OUT = ROOT / "configs"

SECRET = "CHANGE_ME"


# --------------------------------------------------------------------------- helpers

def load(path: Path = DESIGN) -> dict:
    with path.open() as fh:
        return json.load(fh)


def net(cidr: str) -> ipaddress.IPv4Network:
    return ipaddress.ip_network(cidr, strict=True)


def mask(cidr: str) -> str:
    return str(net(cidr).netmask)


def wildcard(cidr: str) -> str:
    return str(net(cidr).hostmask)


def host(cidr: str, n: int) -> str:
    """nth usable host of a subnet (1-based)."""
    return str(net(cidr).network_address + n)


def vip(cidr: str) -> str:      # HSRP virtual gateway, always .1
    return host(cidr, 1)


def core_ip(cidr: str, core: str) -> str:   # CORE1 = .2, CORE2 = .3
    return host(cidr, 2 if core == "CORE1" else 3)


def vlan_list(ids) -> str:
    return ",".join(str(i) for i in sorted(ids))


def block(lines) -> str:
    return "\n".join(lines) + "\n"


def vlan_by_name(site: dict, name: str) -> dict:
    for v in site["vlans"]:
        if v["name"] == name:
            return v
    raise KeyError(name)


